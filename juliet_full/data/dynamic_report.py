#!/usr/bin/env python3
"""Score the dynamic reference-line predictions and write results/dynamic_report.md + dynamic_scores.json.

Scores come from juliet_full/analysis/score.py (owned by the static lane; called read-only) on the eval set.
Besides the scores, the report checks: dynamic_enhanced false positives on good units per part; which part
detects which bad units; per-unit invariance layer1 vs stress vs placebo; agreement with the stage-1/3 verify
verdicts; non-leak ASan errors; latency (lat300_c1) median/p90 per method.

  python3 dynamic_report.py [--run-id full_v1] [--bootstrap 2000]
"""
from __future__ import annotations

import argparse
import json
import statistics
import subprocess
import sys
from collections import Counter, defaultdict
from pathlib import Path

DATA_DIR = Path(__file__).resolve().parent
JULIET_FULL = DATA_DIR.parent
BUILD = DATA_DIR / "build"
RESULTS = DATA_DIR / "results"
SCORE = JULIET_FULL / "analysis" / "score.py"
sys.path.insert(0, str(DATA_DIR))
from dynamic_runs import LAYERS  # noqa: E402

METHODS = ("asan_lsan", "asan_lsan_default", "valgrind", "dynamic_enhanced")


def read(path: Path) -> list[dict]:
    return [json.loads(l) for l in path.read_text().splitlines() if l.strip()]


def score(pred: Path, layer: str, bootstrap: int) -> dict:
    out = RESULTS / "scores" / f"{pred.parent.parent.name}__{layer}__{pred.stem}.json"
    out.parent.mkdir(parents=True, exist_ok=True)
    cmd = [sys.executable, str(SCORE), "--pred", str(pred), "--units", str(BUILD / LAYERS[layer][0]),
           "--set", "eval", "--json", "--bootstrap", str(bootstrap), "--out", str(out)]
    subprocess.run(cmd, check=True, stdout=subprocess.DEVNULL)
    return json.loads(out.read_text())


def pct(values: list[float], q: float) -> float:
    values = sorted(values)
    return values[min(len(values) - 1, int(round(q * (len(values) - 1))))]


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--run-id", default="full_v1")
    parser.add_argument("--bootstrap", type=int, default=2000)
    args = parser.parse_args()
    units = {layer: {u["unit_id"]: u for u in read(BUILD / f)} for layer, (f, _) in LAYERS.items()}
    preds: dict[tuple[str, str], dict[str, dict]] = {}
    scores: dict[str, dict] = {}
    for layer, (_, methods) in LAYERS.items():
        for method in methods:
            path = RESULTS / method / layer / f"{args.run_id}.jsonl"
            if not path.exists():
                continue
            preds[(method, layer)] = {r["unit_id"]: r for r in read(path)}
            scores[f"{method}/{layer}"] = score(path, layer, args.bootstrap)
    lines = ["# Dynamic reference line (data lane stage 4)", "",
             f"Generated by `juliet_full/data/dynamic_report.py` from `results/<method>/<layer>/{args.run_id}.jsonl`; "
             "scores by `juliet_full/analysis/score.py --set eval` (2,656 units; family-cluster bootstrap CI).", "",
             "## Scores (eval)", "",
             "| method | layer | P | R | F1 (leak) | macro-F1 [95% CI] | status |", "|---|---|---|---|---|---|---|"]
    for key, s in scores.items():
        e = s["end_to_end"]
        ci = s.get("bootstrap", {}).get("ci95", {}).get("macro_f1")
        ci_s = f" [{ci[0]:.3f}, {ci[1]:.3f}]" if ci else ""
        method, layer = key.split("/")
        lines.append(f"| {method} | {layer} | {e['precision_leak']:.3f} | {e['recall_leak']:.3f} | {e['f1_leak']:.3f} | "
                     f"{e['macro_f1']:.3f}{ci_s} | {s['status_counts']} |")
    for dim in ("by_mechanism", "by_flow_category"):
        keys = sorted({k for s in scores.values() for k in s[dim]})
        lines += ["", f"## Layer 1 eval {dim.replace('by_', 'by ')}: detected bad / bad, flagged good / good", "",
                  "| method | " + " | ".join(keys) + " |", "|---|" + "---|" * len(keys)]
        for method in METHODS:
            s = scores.get(f"{method}/layer1")
            if not s:
                continue
            cells = []
            for k in keys:
                c = s[dim].get(k)
                cells.append(f"{c['tp']}/{c['tp'] + c['fn']}, {c['fp']}/{c['fp'] + c['tn']}" if c else "-")
            lines.append(f"| {method} | " + " | ".join(cells) + " |")

    # dynamic_enhanced: false-positive checks and the part that detects each bad unit (all sets)
    lines += ["", "## dynamic_enhanced checks (all 3,316 units per layer, dev + eval)", ""]
    for layer in ("layer1", "stress", "placebo"):
        p = preds.get(("dynamic_enhanced", layer))
        if not p:
            continue
        us = units[layer]
        goods = [r for uid, r in p.items() if us[uid]["label"] == "good"]
        bads = [r for uid, r in p.items() if us[uid]["label"] == "bad"]
        rf_good = [r for r in goods if us[r["unit_id"]]["mechanism"] == "realloc_fail"]
        part_fp = Counter(part for r in goods for part in r["extra"]["leak_parts"])
        lines += [f"### {layer}", "",
                  f"- good units flagged: {sum(r['pred'] == 1 for r in goods)}/{len(goods)} "
                  f"(per part: {dict(part_fp) or 'none'})",
                  f"- realloc_fail goods: injection happened in {sum(r['extra']['parts']['realloc']['injected_runs'] > 0 for r in rf_good)}"
                  f"/{len(rf_good)} units, leak under injection in {sum(r['extra']['parts']['realloc']['leak_runs'] > 0 for r in rf_good)}",
                  f"- good units where use_globals=0 shows non-unit blocks (stdio buffers, filtered by attribution): "
                  f"{sum(r['extra']['parts']['globals']['other_blocks_max'] > 0 for r in goods)}/{len(goods)}"]
        first = Counter()
        for r in bads:
            parts = r["extra"]["parts"]
            if parts["base"]["leak_runs"] == 8:
                first["base, all 8 seeds"] += 1
            elif parts["base"]["leak_runs"]:
                first["base, some seeds (random branch)"] += 1
            elif parts["globals"]["leak_runs"]:
                first["globals only"] += 1
            elif parts["realloc"]["leak_runs"]:
                first["realloc injection only"] += 1
            else:
                first["missed"] += 1
        missed = sorted(Counter(us[r["unit_id"]]["mechanism"] + "/" + us[r["unit_id"]]["variant"]
                                for r in bads if r["pred"] != 1).items())
        lines += [f"- bad units by detecting part: {dict(first)}", f"- missed bad (mechanism/variant): {dict(missed) or 'none'}", ""]
    if ("valgrind", "layer1") in preds:
        p = preds[("valgrind", "layer1")]
        us = units["layer1"]
        reach = Counter((us[u]["label"], us[u]["variant"] in ("45", "68")) for u, r in p.items()
                        if r["extra"].get("still_reachable_unit", 0) > 0)
        lines += ["## valgrind still reachable (layer 1, all units)", "",
                  f"- units with still-reachable bytes allocated in the unit, by (label, variant 45/68): {dict(reach)}",
                  f"- good units with any still-reachable bytes: "
                  f"{sum(r['extra'].get('still_reachable', 0) > 0 for u, r in p.items() if us[u]['label'] == 'good')}",
                  f"- invalid/mismatched free reported: {sum(bool(r['extra'].get('invalid_free')) for r in p.values())} units", ""]

    # invariance and agreement
    lines += ["## Invariance across layers (same unit_id; all units)", "",
              "| method | layer pair | same pred | differing units (variant counts) |", "|---|---|---|---|"]
    for method in ("asan_lsan", "dynamic_enhanced"):
        a = preds.get((method, "layer1"))
        for other in ("stress", "placebo"):
            b = preds.get((method, other))
            if not a or not b:
                continue
            diff = [u for u in a if a[u]["pred"] != b[u]["pred"]]
            var = Counter(units["layer1"][u]["variant"] for u in diff)
            lines.append(f"| {method} | layer1 vs {other} | {len(a) - len(diff)}/{len(a)} | {dict(var) or '-'} |")
    lines += ["", "## Agreement with the stage-1/3 verify verdicts (primary LSan, use_stacks=0)", ""]
    ref = {("layer1", r["unit_id"]): r["verify"]["asan_leak"] for r in read(BUILD / "verify_results.jsonl")
           if r["layer"] == "layer1"}
    ref.update({(("stress" if r["layer"] == "layer3" else r["layer"]), r["unit_id"]): r["verify"]["asan_leak"]
                for r in read(BUILD / "verify_layer3.jsonl")})
    for layer in ("layer1", "stress", "placebo"):
        p = preds.get(("asan_lsan", layer))
        if not p:
            continue
        diff = [u for u, r in p.items() if bool(r["pred"]) != bool(ref.get((layer, u)))]
        var = Counter(units[layer][u]["variant"] for u in diff)
        lines.append(f"- asan_lsan {layer}: {len(p) - len(diff)}/{len(p)} equal; differing by variant {dict(var) or '-'} "
                     "(stage 1 ran variant 12 up to 6 times, here 1 run)")
    errs = Counter()
    for (method, layer), p in preds.items():
        for r in p.values():
            e = r["extra"].get("asan_error") or (r["extra"].get("asan_errors") or [None])[0]
            if e:
                errs[(method, layer, e, units[layer][r["unit_id"]]["variant"])] += 1
    lines += ["", "## Non-leak ASan errors (pred counts leak reports only)", ""]
    lines += [f"- {m} {l}: {e} in {n} units (variant {v})" for (m, l, e, v), n in sorted(errs.items())] or ["- none"]

    # latency
    lat = {}
    lines += ["", "## Latency (lat300_c1: latency300 subset, layer 1, concurrency 1, compile + executions)", ""]
    for method in ("asan_lsan", "valgrind", "dynamic_enhanced"):
        path = RESULTS / method / "layer1" / "lat300_c1.jsonl"
        if not path.exists():
            continue
        rows = read(path)
        meta = json.loads(path.with_suffix(".meta.json").read_text())
        vals = [r["latency_s"] for r in rows if r["latency_s"] is not None]
        lat[method] = {"n": len(vals), "median_s": round(statistics.median(vals), 4), "p90_s": round(pct(vals, 0.9), 4),
                       "loadavg_start": meta["loadavg_start"], "loadavg_end": meta["loadavg_end"]}
    if lat:
        lines += ["| method | n | median s | p90 s | load start → end (1/5/15 min) |", "|---|---|---|---|---|"]
        for m, v in lat.items():
            lines.append(f"| {m} | {v['n']} | {v['median_s']:.3f} | {v['p90_s']:.3f} | "
                         f"{'/'.join(f'{x:.1f}' for x in v['loadavg_start'])} → {'/'.join(f'{x:.1f}' for x in v['loadavg_end'])} |")
    else:
        lines.append("- not measured yet")
    (RESULTS / "dynamic_report.md").write_text("\n".join(lines) + "\n")
    summary = {k: {"end_to_end": v["end_to_end"], "ci95": v.get("bootstrap", {}).get("ci95"),
                   "by_mechanism": v["by_mechanism"], "by_flow_category": v["by_flow_category"],
                   "status_counts": v["status_counts"]} for k, v in scores.items()}
    (RESULTS / "dynamic_scores.json").write_text(json.dumps({"scores": summary, "latency": lat}, indent=1) + "\n")
    print("\n".join(lines))


if __name__ == "__main__":
    main()

#!/usr/bin/env python3
"""Recompile and rerun every layer-3 (stress) and placebo unit; compare with the stage-1 verdict.

Per unit: gcc/g++ ASan build, clang/clang++ 23 compile+link, ASan/LSan run with the stage-1
primary options (LSAN use_stacks=0; variant 12 up to RANDOM_RUNS runs) via
verify_labels.verify_unit. The verdict must equal the layer-1 verdict from
build/verify_results.jsonl, and no ASan error other than a leak may appear that the layer-1
unit did not already have (Juliet's own variant-12 bad-free).

Writes build/verify_layer3.jsonl ({layer: layer3|placebo, unit_id, verify, stage1_asan_leak,
same_verdict}) and build/verify_layer3_report.md. Default 6 jobs (the static lane shares the box).
Run with nohup; full run is about 15-20 min at 6 jobs.
"""
from __future__ import annotations

import argparse
import json
import os
import re
import shutil
import subprocess
import sys
import tempfile
import time
from collections import Counter, defaultdict
from concurrent.futures import ThreadPoolExecutor
from pathlib import Path

DATA_DIR = Path(__file__).resolve().parent
sys.path.insert(0, str(DATA_DIR))
import verify_labels  # noqa: E402

BUILD = DATA_DIR / "build"
LAYER_FILES = {"layer3": BUILD / "layer3.jsonl", "placebo": BUILD / "placebo.jsonl"}
OUT = BUILD / "verify_layer3.jsonl"
REPORT = BUILD / "verify_layer3_report.md"
OTHER_ERROR = "other ASan error"
NOT_LOCATED = "non-leak ASan error at an inserted statement or not located"


def stage1() -> dict[str, dict]:
    rows = [json.loads(l) for l in (BUILD / "verify_results.jsonl").read_text().splitlines()]
    return {r["unit_id"]: r["verify"] for r in rows if r["layer"] == "layer1"}


def has_other_error(v: dict) -> bool:
    return OTHER_ERROR in (v.get("note") or "")


def check(layer: str, unit: dict, v: dict, ref: dict) -> dict:
    problems = []
    if not v["compile_gcc"]:
        problems.append("gcc compile failed")
    if not v["compile_clang"]:
        problems.append("clang compile failed")
    if v["asan_leak"] != ref["asan_leak"]:
        problems.append(f"verdict {v['asan_leak']} != stage-1 {ref['asan_leak']}"
                        + (" (variant 12 random branch)" if unit["variant"] == "12" else ""))
    if has_other_error(v) and not has_other_error(ref):
        problems.append("non-leak ASan error not seen in stage 1"
                        + (" (variant 12 random branch)" if unit["variant"] == "12" else ""))
    return {"layer": layer, "unit_id": unit["unit_id"], "verify": v, "stage1_asan_leak": ref["asan_leak"],
            "same_verdict": v["asan_leak"] == ref["asan_leak"], "problems": problems}


def locate_errors(results: list[dict], units: dict, workroot: Path, tries: int = 20) -> None:
    """For every unit with a non-leak ASan error: rerun until it shows, record the source line of the
    failing free/delete and whether it is an inserted dead statement (it must be a real one)."""
    env = dict(os.environ, ASAN_OPTIONS="detect_leaks=1:abort_on_error=0:exitcode=23",
               LSAN_OPTIONS="exitcode=23:use_stacks=0")
    for r in results:
        if not has_other_error(r["verify"]):
            continue
        u = units[(r["layer"], r["unit_id"])]
        exe = workroot / f"{r['layer']}__{r['unit_id']}"
        gnu = "g++" if u["build"]["compiler"] == "g++" else "gcc"
        verify_labels.run(verify_labels.compile_cmd(u, gnu, exe, True), u["program_dir"], 120)
        site = None
        for _ in range(tries):
            p = subprocess.run([str(exe)], cwd=u["program_dir"], env=env, stdin=subprocess.DEVNULL,
                               capture_output=True, timeout=verify_labels.TIMEOUT_S)
            err = p.stderr.decode("utf-8", "replace")
            m = re.search(r"ERROR: AddressSanitizer: (?!.*LeakSanitizer)(.*?)(?: on address|:|$)", err, re.M)
            frame = re.search(r" in \S+ \S*/(unit_\d+\.(?:c|cpp|h)):(\d+)", err)
            if m and frame:
                f, line = frame.group(1), int(frame.group(2))
                dead = {(i["file"], i["file_line"]) for i in u["transform"]["inserted"]}
                text = (Path(u["program_dir"]) / f).read_text().splitlines()[line - 1].strip()
                site = {"error": m.group(1), "file": f, "file_line": line, "stmt": text,
                        "inserted_dead_stmt": (f, line) in dead}
                break
            time.sleep(1.05)
        r["error_site"] = site
        if (site is None or site["inserted_dead_stmt"]) and NOT_LOCATED not in r["problems"]:
            r["problems"].append(NOT_LOCATED)


def write_report(results: list[dict], units: dict) -> str:
    lines = ["# Layer 3 (stress) and placebo: recompile + ASan/LSan check against stage 1", "",
             "Generated by `juliet_full/data/verify_layer3.py` (gcc/g++ 13 -fsanitize=address -O0, clang 23 compile+link, "
             "ASAN detect_leaks=1, LSAN use_stacks=0 as in the stage-1 primary run; variant 12 up to 6 runs).", "",
             "| layer | units | gcc ok | clang ok | same verdict as stage 1 | leak (bad) | leak (good) | non-leak ASan error (stage 1 had none) | ... at an inserted stmt |",
             "|---|---|---|---|---|---|---|---|---|"]
    for layer in LAYER_FILES:
        rs = [r for r in results if r["layer"] == layer]
        if not rs:
            continue
        bad = [r for r in rs if r["unit_id"].endswith("__bad")]
        good = [r for r in rs if r["unit_id"].endswith("__good")]
        lines.append(f"| {layer} | {len(rs)} | {sum(r['verify']['compile_gcc'] for r in rs)} | "
                     f"{sum(r['verify']['compile_clang'] for r in rs)} | {sum(r['same_verdict'] for r in rs)} | "
                     f"{sum(bool(r['verify']['asan_leak']) for r in bad)}/{len(bad)} | "
                     f"{sum(bool(r['verify']['asan_leak']) for r in good)}/{len(good)} | "
                     f"{sum(any(p.startswith('non-leak ASan error not seen') for p in r['problems']) for r in rs)} | "
                     f"{sum(bool((r.get('error_site') or {}).get('inserted_dead_stmt')) for r in rs)} |")
    lines += ["", "## Verdict by mechanism (bad units leak reported, layer3 / placebo / stage 1)", "",
              "| mechanism | bad units | layer3 | placebo | stage 1 |", "|---|---|---|---|---|"]
    table = defaultdict(Counter)
    for r in results:
        if r["unit_id"].endswith("__bad"):
            mech = units[(r["layer"], r["unit_id"])]["mechanism"]
            table[mech][r["layer"]] += bool(r["verify"]["asan_leak"])
            if r["layer"] == "layer3":
                table[mech]["n"] += 1
                table[mech]["stage1"] += bool(r["stage1_asan_leak"])
    for mech, c in sorted(table.items()):
        lines.append(f"| {mech} | {c['n']} | {c['layer3']} | {c['placebo']} | {c['stage1']} |")
    problems = [r for r in results if r["problems"]]
    lines += ["", f"## Units with a problem ({len(problems)})", ""]
    reasons = Counter((r["layer"], p) for r in problems for p in r["problems"])
    for (layer, p), n in sorted(reasons.items()):
        ids = [r["unit_id"] for r in problems if r["layer"] == layer and p in r["problems"]][:10]
        lines.append(f"- {layer}: {p}: {n} -> " + ", ".join(ids))
    if not problems:
        lines.append("- none")
    located = [r for r in results if "error_site" in r]
    if located:
        sites = Counter((r["layer"], (r["error_site"] or {}).get("error"), (r["error_site"] or {}).get("stmt"),
                         (r["error_site"] or {}).get("inserted_dead_stmt")) for r in located)
        lines += ["", "## Non-leak ASan errors located (rerun until the error shows)", "",
                  "| layer | error | failing statement | at an inserted dead statement | units |", "|---|---|---|---|---|"]
        for (layer, err, stmt, dead), n in sorted(sites.items(), key=str):
            lines.append(f"| {layer} | {err} | `{stmt}` | {dead} | {n} |")
        lines += ["", "All are variant-12 bad units: Juliet's bad function frees the `ALLOCA` buffer on one random path "
                  "(the same error as in stage 1, where 16 bad units hit that path). Whether a run takes that path "
                  "depends on `time(NULL)`, so the set of units that show it differs between runs."]
    return "\n".join(lines) + "\n"


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--jobs", type=int, default=6)
    parser.add_argument("--limit", type=int, default=None, help="only the first N units per layer (smoke test)")
    parser.add_argument("--report-only", action="store_true")
    parser.add_argument("--locate-errors", action="store_true",
                        help="only rerun the units with a non-leak ASan error and record the failing statement")
    args = parser.parse_args()
    units = {}
    jobs = []
    for layer, path in LAYER_FILES.items():
        rows = [json.loads(l) for l in path.read_text().splitlines()][: args.limit]
        for u in rows:
            units[(layer, u["unit_id"])] = u
            jobs.append((layer, u))
    if args.report_only or args.locate_errors:
        results = [json.loads(l) for l in OUT.read_text().splitlines()]
        ref = stage1()
        for i, r in enumerate(results):  # recompute the checks (problem wording) from the stored verdicts
            extra = {k: r[k] for k in ("error_site",) if k in r}
            results[i] = {**check(r["layer"], units[(r["layer"], r["unit_id"])], r["verify"], ref[r["unit_id"]]), **extra}
            if extra and (extra["error_site"] is None or extra["error_site"]["inserted_dead_stmt"]):
                results[i]["problems"].append(NOT_LOCATED)
        if args.locate_errors:
            workroot = Path(tempfile.mkdtemp(prefix="verify3_", dir="/tmp"))
            locate_errors(results, units, workroot)
            shutil.rmtree(workroot, ignore_errors=True)
            OUT.write_text("".join(json.dumps(r, sort_keys=True) + "\n" for r in results))
    else:
        ref = stage1()
        workroot = Path(tempfile.mkdtemp(prefix="verify3_", dir="/tmp"))
        with ThreadPoolExecutor(max_workers=min(args.jobs, 6)) as pool:
            futures = [pool.submit(verify_labels.verify_unit, u, False, workroot) for _, u in jobs]
            results = [check(layer, u, f.result(), ref[u["unit_id"]]) for (layer, u), f in zip(jobs, futures)]
        results.sort(key=lambda r: (r["layer"], r["unit_id"]))
        locate_errors(results, units, workroot)
        shutil.rmtree(workroot, ignore_errors=True)
        OUT.write_text("".join(json.dumps(r, sort_keys=True) + "\n" for r in results))
    text = write_report(results, units)
    if args.limit is None:
        REPORT.write_text(text)
    print(text)


if __name__ == "__main__":
    main()

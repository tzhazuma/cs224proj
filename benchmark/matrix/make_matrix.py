def _validate(rows: list[dict[str, str]], columns: list[str]) -> None:
    seen: set[str] = set()
    for row in rows:
        missing = [column for column in columns if column not in row]
        if missing:
            raise SystemExit(f"{row.get('exp_id')}: missing columns {missing}")
        exp_id = row["exp_id"]
        if exp_id in seen:
            raise SystemExit(f"duplicate exp_id: {exp_id}")
        seen.add(exp_id)
        if row["status"] not in STATUSES:
            raise SystemExit(f"{exp_id}: invalid status {row['status']!r}")


def _write_csv(path: Path, columns: list[str], rows: list[dict[str, str]]) -> None:
    with path.open("w", encoding="utf-8", newline="") as handle:
        writer = csv.DictWriter(handle, fieldnames=columns)
        writer.writeheader()
        writer.writerows(rows)


def _render_markdown(rows: list[dict[str, str]], columns: list[str], title: str) -> str:
    lines = [f"# {title}", "", f"Rows: {len(rows)}. This is a plan, not a result table.", ""]
    for tier in ("A", "B", "A+B"):
        subset = [row for row in rows if row.get("tier", "A") == tier]
        if not subset:
            continue
        lines += [f"## Tier {tier}", "", "| " + " | ".join(columns) + " |", "| " + " | ".join("---" for _ in columns) + " |"]
        for row in subset:
            lines.append("| " + " | ".join(str(row.get(column, "")).replace("|", "\\|") for column in columns) + " |")
        lines.append("")
    return "\n".join(lines)


def main() -> int:
    for row in ROWS + INNOVATION_ROWS:
        row["status"] = STATUS_OVERRIDES.get(row["exp_id"], row["status"])
    _validate(ROWS, COLUMNS)
    _validate(INNOVATION_ROWS, INNOVATION_COLUMNS)
    _write_csv(ROOT / "experiment_matrix.csv", COLUMNS, ROWS)
    _write_csv(ROOT / "innovation_matrix.csv", INNOVATION_COLUMNS, INNOVATION_ROWS)
    (ROOT / "experiment_matrix.md").write_text(
        _render_markdown(ROWS, COLUMNS, "Benchmark experiment matrix"),
        encoding="utf-8",
    )
    (ROOT / "innovation_matrix.md").write_text(
        _render_markdown(INNOVATION_ROWS, INNOVATION_COLUMNS, "Innovation experiment matrix"),
        encoding="utf-8",
    )
    print(f"wrote {len(ROWS)} benchmark rows and {len(INNOVATION_ROWS)} innovation rows")
    return 0



"""Count all CWE labels and generate publication-quality PGFPlots sources.

Run with pap Python; only the standard library is needed. Compile the generated
figures/cwe_distribution_{en,zh}.tex with XeLaTeX to obtain vector PDFs.
The input datasets are never modified. Negative/fixed records are not counted.
"""

from __future__ import annotations

import hashlib
import json
import re
from collections import Counter
from pathlib import Path


HERE = Path(__file__).resolve().parent
PLACEHOLDERS = {"NVD-CWE-noinfo", "NVD-CWE-Other"}


def normalized_labels(raw_labels: list[str]) -> set[str]:
    """Split concatenated numeric CWE IDs and count each label once per row."""
    if not isinstance(raw_labels, list):
        raise ValueError("cwe_list must be an array")
    labels: set[str] = set()
    for raw in raw_labels:
        if not isinstance(raw, str):
            raise ValueError(f"Unexpected CWE label: {raw!r}")
        if re.fullmatch(r"(?:CWE-\d+)+", raw):
            labels.update(re.findall(r"CWE-\d+", raw))
        elif raw in PLACEHOLDERS:
            labels.add(raw)
        else:
            raise ValueError(f"Unrecognized CWE label: {raw!r}")
    if not labels:
        raise ValueError("A vulnerable row has no CWE annotation")
    return labels


def summarize(rows: list[dict]) -> tuple[Counter, dict]:
    counts: Counter = Counter()
    multilabel = []
    expanded = []
    for row in rows:
        if row["is_vulnerable"] is not True:
            raise ValueError("Only vulnerable rows may be counted")
        labels = normalized_labels(row["cwe_list"])
        counts.update(labels)
        if len(labels) > 1:
            multilabel.append(row["idx"])
        if any(re.fullmatch(r"(?:CWE-\d+){2,}", value) for value in row["cwe_list"]):
            expanded.append(row["idx"])
    return counts, {
        "vulnerable_functions": len(rows),
        "numeric_cwe_types": sum(label not in PLACEHOLDERS for label in counts),
        "numeric_cwe_assignments": sum(n for label, n in counts.items() if label not in PLACEHOLDERS),
        "nvd_placeholder_counts": {label: counts[label] for label in sorted(PLACEHOLDERS)},
        "total_label_assignments_including_placeholders": sum(counts.values()),
        "multi_label_function_count": len(multilabel),
        "multi_label_source_indices": sorted(multilabel),
        "concatenated_label_source_indices": sorted(expanded),
    }


def label_sort_key(label: str, counts: list[Counter]) -> tuple:
    # Shared ordering enables direct comparison; tie-break by numeric CWE ID.
    return (-sum(c[label] for c in counts), label in PLACEHOLDERS,
            int(label[4:]) if label not in PLACEHOLDERS else 0, label)


def make_plot_source(language: str, labels: list[str], counts: list[Counter]) -> str:
    chinese = language == "zh"
    preamble = r"""% Generated by build_cwe_figures.py. Do not edit counts manually.
% !TeX program = xelatex
\documentclass[border=3pt]{standalone}
"""
    if chinese:
        preamble += r"\usepackage[UTF8,scheme=plain,fontset=fandol]{ctex}" + "\n"
    else:
        preamble += r"\usepackage{fontspec}" + "\n"
    preamble += r"""\setmainfont{TeX Gyre Termes}
\usepackage{fix-cm}
\usepackage{pgfplots}
\usepgfplotslibrary{groupplots}
\pgfplotsset{compat=1.18}
\definecolor{independentblue}{HTML}{24679B}
\definecolor{pairedorange}{HTML}{C66B29}
\begin{document}
\begin{tikzpicture}
\begin{groupplot}[
    group style={group size=3 by 1,horizontal sep=1.60cm},
    width=5.70cm,height=11.3cm,
    xbar,/pgf/bar width=3.2pt,
    xmin=0,xmax=33,
    ymin=-0.7,ymax=19.7,y dir=reverse,
    xtick={0,10,20,30},
    axis x line*=bottom,axis y line*=left,
    axis line style={black!45},
    tick style={black!45},
    tick label style={font=\fontsize{8}{9}\selectfont},
    yticklabel style={text width=1.55cm,align=right},
    xmajorgrids=true,grid style={black!12},
    title style={font=\fontsize{8.5}{10}\selectfont},
    label style={font=\fontsize{8}{9}\selectfont},
    point meta=x,
    nodes near coords={\pgfmathfloattofixed{\pgfplotspointmeta}\ifdim\pgfmathresult pt>0pt\relax\pgfmathprintnumber[fixed,precision=0]{\pgfplotspointmeta}\fi},
    nodes near coords style={font=\fontsize{7}{8}\selectfont,anchor=west,xshift=0.4pt,text=black!85},
    clip=false,
"""
    preamble += "    xlabel={" + ("漏洞函数数量" if chinese else "Vulnerable functions") + "},\n]\n"
    plot = []
    for panel in range(3):
        part = labels[panel * 20:(panel + 1) * 20]
        ticks = ",".join(map(str, range(len(part))))
        display = [label.replace("NVD-CWE-", "NVD-") for label in part]
        opts = [f"title={{({chr(97 + panel)}) {panel * 20 + 1}--{panel * 20 + len(part)}}}",
                f"ytick={{{ticks}}}", "yticklabels={" + ",".join(display) + "}"]
        if panel == 1:
            opts.append("legend style={at={(0.5,1.13)},anchor=south,legend columns=2,draw=none,font=\\fontsize{8}{10}\\selectfont,/tikz/every even column/.append style={column sep=10pt}}")
        plot.append("\\nextgroupplot[" + ",\n".join(opts) + "]\n")
        for series, color in enumerate(["independentblue", "pairedorange"]):
            shift = "-2.0pt" if series == 0 else "2.0pt"
            coordinates = " ".join(f"({counts[series][label]},{i})" for i, label in enumerate(part))
            plot.append(f"\\addplot+[fill={color},draw={color},/pgf/bar shift={shift}] coordinates {{{coordinates}}};\n")
            if panel == 1:
                legend = (["独立集：160 条漏洞函数", "配对集：200 条漏洞函数"] if chinese else
                          ["Independent: 160 vulnerable functions", "Paired: 200 vulnerable functions"])[series]
                plot.append("\\addlegendentry{" + legend + "}\n")
    return preamble + "".join(plot) + r"""\end{groupplot}
\end{tikzpicture}
\end{document}
"""


def main() -> None:
    paths = [HERE.parent / "datasets" / "independent_200.json",
             HERE.parent / "datasets" / "vulnerable_fixed_200_pairs.json"]
    independent, paired = [json.loads(path.read_text(encoding="utf-8")) for path in paths]
    independent_rows = [row for row in independent["samples"] if row["is_vulnerable"]]
    paired_rows = [pair["vulnerable"] for pair in paired["pairs"]]
    summaries = [summarize(rows) for rows in [independent_rows, paired_rows]]
    counts = [item[0] for item in summaries]
    labels = sorted(set(counts[0]) | set(counts[1]), key=lambda label: label_sort_key(label, counts))
    # The three panels share one axis scale and contain every observed label.
    if len(labels) > 60:
        raise ValueError("More than 60 labels: extend the three-panel layout before exporting")
    if max(c for counter in counts for c in counter.values()) > 30:
        raise ValueError("Increase the common x-axis limit before exporting")
    stats = {
        "counting_unit": "Vulnerable functions carrying each normalized label; at most once per function per label",
        "excluded_from_counts": "40 independent negatives and all 200 fixed counterparts",
        "normalization": "Split strings matching (CWE-<digits>)+ into numeric CWE IDs; deduplicate within each function; preserve NVD placeholders",
        "ordering": "Descending combined count, then numeric CWE ID; NVD placeholders ordered last within ties",
        "source_sha256": {p.name: hashlib.sha256(p.read_bytes()).hexdigest() for p in paths},
        "independent": summaries[0][1],
        "paired": summaries[1][1],
        "union_numeric_cwe_types": sum(label not in PLACEHOLDERS for label in labels),
        "displayed_categories_including_placeholders": len(labels),
        "counts": [{"label": label, "independent": counts[0][label], "paired": counts[1][label]}
                   for label in labels],
    }
    figures = HERE / "figures"
    figures.mkdir(exist_ok=True)
    (figures / "cwe_counts.json").write_text(json.dumps(stats, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    for language in ["zh", "en"]:
        (figures / f"cwe_distribution_{language}.tex").write_text(make_plot_source(language, labels, counts), encoding="utf-8")
    print(json.dumps({"vulnerable_functions": [len(independent_rows), len(paired_rows)],
                      "numeric_cwe_types": [s[1]["numeric_cwe_types"] for s in summaries],
                      "numeric_cwe_types_in_union": stats["union_numeric_cwe_types"],
                      "displayed_categories": len(labels),
                      "label_assignments": [sum(c.values()) for c in counts]}, indent=2))


if __name__ == "__main__":
    main()
